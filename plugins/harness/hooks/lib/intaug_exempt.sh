# 입력 전체가 인자 없는 슬래시 명령(/이름 한 토큰)인지 판정하는 ointaug 면제 정본 함수
# 사용: intaug_is_bare_slash "<프롬프트>"  → 면제 대상이면 rc=0, 아니면 rc=1
#   앞뒤 공백·개행(실문자 및 JSON 이스케이프 \n \t \r)을 제거하고 플러그인 접두사(harness: 등)를 정규화한 뒤
#   ^/이름$ (이름은 영숫자·_·-·: , 첫 글자는 : 제외) 에 완전 일치할 때만 면제한다. 인자·일반 문장·빈 입력은 면제하지 않는다.
intaug_is_bare_slash() {
  local _p="$1"
  while [[ "$_p" == [[:space:]]* || "$_p" == \\n* || "$_p" == \\t* || "$_p" == \\r* ]]; do
    if [[ "$_p" == \\* ]]; then _p="${_p:2}"; else _p="${_p:1}"; fi
  done
  while [[ "$_p" == *[[:space:]] || "$_p" == *\\n || "$_p" == *\\t || "$_p" == *\\r ]]; do
    if [[ "$_p" == *[[:space:]] ]]; then _p="${_p%?}"; else _p="${_p%??}"; fi
  done
  if [[ "$_p" =~ ^/([A-Za-z0-9_-]+:)? ]]; then _p="/${_p:${#BASH_REMATCH[0]}}"; fi
  [[ "$_p" =~ ^/[A-Za-z0-9_-][A-Za-z0-9_:-]*$ ]]
}
