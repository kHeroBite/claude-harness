    out("PASS")

# V3-pre — 코드블록(``` 펜스) 구간 제거 (오탐 저감, 저위험)
# 펜스 안의 예시 코드/샘플 출력은 사용자에게 던지는 질문이 아니다.
# ★꼬리 3줄을 자르기 전에★ 제거해야 한다 — 펜스가 꼬리 창을 차지해버리면
# 정작 판정해야 할 실제 맺음말이 창 밖으로 밀려나기 때문이다.
# 홀수 개(미닫힘) 펜스는 마지막 펜스부터 끝까지를 코드로 간주해 함께 제거한다.
