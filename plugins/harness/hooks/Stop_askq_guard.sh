    AUTO_ON = False

try:
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        # 42MB 실측 — 전체 로드 금지. 꼬리 3000행만 유지한다.
        tail = deque(f, maxlen=MAX_LINES)
except Exception:
    out("UNKNOWN")

lines = list(tail)
if not lines:
    out("UNKNOWN")

rows = []
for ln in lines:
    ln = ln.strip()
    if not ln:
        continue
    try:
        rows.append(json.loads(ln))   # 쓰기 중 부분 행은 조용히 skip
    except Exception:
        continue

if not rows:
    out("UNKNOWN")


def content_of(row):
    try:
        msg = row.get("message")
        if not isinstance(msg, dict):
            return None
        return msg.get("content")
    except Exception:
        return None


def is_turn_boundary(row):
    """새 사용자 턴의 시작인가. report_guard.sh 의 is_turn_boundary() 와 동형.

    type=="user" AND isMeta 아님 AND content 가 tool_result 전용이 아닌 행.
    """
    if row.get("type") != "user":
        return False
    if row.get("isMeta"):
        return False
    c = content_of(row)
    if isinstance(c, str):
        return c.strip() != ""
    if isinstance(c, list):
        if not c:
            return False
        for it in c:
            if not (isinstance(it, dict) and it.get("type") == "tool_result"):
                return True
        return False
    return False


# --- 마지막 턴 경계 위치 탐색 ---
last_idx = -1
for i, r in enumerate(rows):
    if is_turn_boundary(r):
        last_idx = i

if last_idx < 0:
    out("UNKNOWN")

# --- 마지막 턴 경계 이후의 assistant 응답 수집 (도구 호출 + 마지막 text 블록) ---
tools = []
last_text = ""
for r in rows[last_idx + 1:]:
    if r.get("type") != "assistant":
        continue
    c = content_of(r)
    if not isinstance(c, list):
        continue
    for it in c:
        if not isinstance(it, dict):
            continue
        ty = it.get("type")
        if ty == "tool_use":
            n = it.get("name")
            if isinstance(n, str) and n:
                tools.append(n)
        elif ty == "text":
            t = it.get("text")
            if isinstance(t, str) and t.strip():
                last_text = t  # 마지막 text 블록으로 계속 갱신

# V2 — 이번 턴에 AskUserQuestion 을 이미 호출했으면 통과
# [c41-odev4] ★역방향★: auto=ON 이면 오히려 이것이 차단 사유가 된다.
#   auto(자율완주) 계약은 "사용자 확인 없이 끝까지 간다" 이므로, 질문한 채로
